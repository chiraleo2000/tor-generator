def get_table_text(table):
    lines = []
    for row in table.rows:
        cells = [c.text.strip().replace('\n', ' ') for c in row.cells]
        lines.append(' | '.join(cells))
    return '\n'.join(lines)

blocks = []
body = doc.element.body
for child in body:
    tag = child.tag.split('}')[-1]
    if tag == 'p':
        p = DocxParagraph(child, doc)
        blocks.append({'type': 'para', 'text': p.text.strip()})
    elif tag == 'tbl':
        t = DocxTable(child, doc)
        blocks.append({'type': 'table', 'text': get_table_text(t)})

print(f"Total blocks: {len(blocks)}")

# ─────────────────────────────────────────────────────────────
# 2. Helpers
# ─────────────────────────────────────────────────────────────
def find_block(marker, start=0, end=None):
    if end is None:
        end = len(blocks)
    for i in range(start, end):
        if marker in blocks[i]['text']:
            return i
    return -1

def collect_between(si, ei):
    parts = []
    for b in blocks[si:ei]:
        if b['type'] == 'table':
            parts.append('[ตาราง]\n' + b['text'])
        elif b['text']:
            parts.append(b['text'])
    return '\n'.join(parts).strip()

def extract_in(ch_start, ch_end, sec_marker, next_markers, skip_first=True):
    si = find_block(sec_marker, ch_start, ch_end)
    if si == -1:
        return ''
    if skip_first:
        si += 1
    ei = ch_end
    for nm in next_markers:
        if nm:
            idx = find_block(nm, si, ch_end)
            if idx != -1 and idx < ei:
                ei = idx
    return collect_between(si, ei)

