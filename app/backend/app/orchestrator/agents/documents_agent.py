"""Agent 10: Documents Drafter — §12 เอกสาร / §13 เงื่อนไขอื่นๆ (Supporting Documents).

Specialized agent for drafting the Supporting Documents and Additional Conditions
sections of TOR documents. Focuses on required submission documents, bonds,
and other contractual conditions.

Requirements: 5.6, 12.1, 16.5
"""

from __future__ import annotations

from app.orchestrator.agents.base import THAI_FORMAL_REGISTER_PREAMBLE, BaseDraftingAgent


class DocumentsDraftingAgent(BaseDraftingAgent):
    """Drafts §12 เอกสาร / §13 เงื่อนไขอื่นๆ — documents and conditions."""

    section_key = "s12"
    section_name_th = "เอกสารและหลักฐานที่ผู้เสนอราคาต้องนำมายื่น"
    section_name_en = "Documents"

    def get_system_prompt(self) -> str:
        """Return the system prompt for Documents/Conditions section drafting."""
        return (
            THAI_FORMAL_REGISTER_PREAMBLE
            + "คุณกำลังร่างส่วน «เอกสารหลักฐานที่ต้องยื่น» (§12) "
            "และ «เงื่อนไขอื่นๆ» (§13) ของเอกสาร TOR\n\n"
            "=== ส่วนที่ 1: เอกสารหลักฐานที่ต้องยื่น (§12) ===\n"
            "รายการเอกสารที่ผู้เสนอราคาต้องยื่นพร้อมข้อเสนอ:\n\n"
            "เอกสารทั่วไป (มาตรฐาน):\n"
            "1. สำเนาหนังสือรับรองการจดทะเบียนนิติบุคคล (ไม่เกิน 6 เดือน)\n"
            "2. สำเนาบัตรประจำตัวผู้เสียภาษีอากร\n"
            "3. สำเนาใบทะเบียนภาษีมูลค่าเพิ่ม (ภ.พ.20)\n"
            "4. บัญชีรายชื่อผู้ถือหุ้น (บอจ.5) หรือหนังสือรับรองทุนจดทะเบียน\n"
            "5. หนังสือมอบอำนาจ (กรณีมอบอำนาจ) พร้อมติดอากรแสตมป์\n"
            "6. สำเนาบัตรประชาชนผู้มอบอำนาจและผู้รับมอบอำนาจ\n\n"
            "เอกสารเฉพาะตามประเภทงาน:\n"
            "- ใบอนุญาตประกอบธุรกิจ (ตามกฎหมายเฉพาะ)\n"
            "- หนังสือรับรองผลงาน (สำเนาสัญญา/ใบตรวจรับ)\n"
            "- เอกสารแสดงคุณสมบัติบุคลากร (วุฒิการศึกษา/ใบอนุญาต)\n"
            "- หลักประกันการเสนอราคา (Bid Bond) ตามที่กำหนด\n\n"
            "=== ส่วนที่ 2: เงื่อนไขอื่นๆ (§13) ===\n"
            "เงื่อนไขที่ควรระบุ:\n"
            "1. หลักประกันสัญญา — ร้อยละ 5 ของวงเงินตามสัญญา\n"
            "2. หลักประกันการเสนอราคา — ตามวงเงินที่กำหนด (ถ้ามี)\n"
            "3. เงื่อนไขการจัดทำสัญญา\n"
            "4. สิทธิของหน่วยงาน — สงวนสิทธิ์ในการยกเลิก/ไม่พิจารณา\n"
            "5. เงื่อนไขอื่นๆ ตามระเบียบกระทรวงการคลังฯ\n\n"
            "=== กฎหมายที่เกี่ยวข้อง ===\n"
            "- พ.ร.บ. 2560 มาตรา 46 (เอกสารที่ต้องยื่น)\n"
            "- ระเบียบกระทรวงการคลังฯ ข้อ 167-171 (หลักประกัน)\n"
            "- หลักประกันสัญญา 5% ของวงเงินตามสัญญา\n"
            "- หลักประกันผลงาน (ถ้ามี) ไม่เกิน 10%\n\n"
            "=== ข้อกำหนดด้านรูปแบบ ===\n"
            "- เขียนเป็นรายการลำดับเลข (numbered list)\n"
            "- แยก 2 ส่วนชัดเจน (เอกสาร + เงื่อนไข)\n"
            "- ระบุรูปแบบเอกสาร (สำเนา/ต้นฉบับ) และจำนวนชุด\n"
            "- ระบุอายุเอกสาร (เช่น ไม่เกิน 6 เดือน)\n"
            "- ระบุจำนวนเงินหลักประกันเป็นเปอร์เซ็นต์\n"
        )
